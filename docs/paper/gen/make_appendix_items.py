"""Appendix A item table, generated from the stimulus file used at run time.

Source: data/stimuli_RQ3.csv (produced by analysis/rq3/make_stimuli_rq3.py).
Output: docs/paper/gen/items.tex, which main.tex \\input{}s.
"""
import pandas as pd
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
OUT = Path(__file__).resolve().parent / 'items.tex'
ORDER = (['chung-1', 'chung-2', 'chung-3', 'chung-4',
          'ling-fix-1', 'ling-fix-2', 'ling-fix-4']
         + [f'llm-{i}' for i in range(1, 9)])

def tex(x):
    if pd.isna(x) or str(x).strip() in ('', 'nan'):
        return '---'
    s = str(x)
    for a, b in [('\\', r'\textbackslash{}'), ('&', r'\&'), ('%', r'\%'), ('$', r'\$'),
                 ('#', r'\#'), ('_', r'\_'), ('{', r'\{'), ('}', r'\}'),
                 ('~', r'\textasciitilde{}'), ('^', r'\textasciicircum{}')]:
        s = s.replace(a, b)
    return s

d = pd.read_csv(ROOT / 'data' / 'stimuli_RQ3.csv')
wide = d.pivot_table(index='label', columns='prefix', values='org_used', aggfunc='first')
meta = d.drop_duplicates('label').set_index('label')

rows = []
for label in ORDER:
    if label not in meta.index:
        continue
    m = meta.loc[label]
    org_r = tex(wide.at[label, 'R']) if 'R' in wide.columns else '---'
    org_i = tex(wide.at[label, 'I']) if 'I' in wide.columns else '---'
    qud = tex(m.QUD)
    qud_row = rf'question raised & \emph{{{qud}}} \\' + '\n' if qud != '---' else ''
    rows.append(
        rf"""\textbf{{\texttt{{{tex(label)}}}}}\quad\emph{{{tex(m.kind)}}}\hfill\texttt{{{tex(m.scenario_id)}}}\\[1pt]
\begin{{tabular}}{{@{{}}p{{0.155\linewidth}}p{{0.815\linewidth}}@{{}}}}
\texttt{{ORG}} in $R$ & {org_r} \\
\texttt{{ORG}} in $I$ & {org_i} \\
evidence $e$ & {tex(m.e)} \\
$h_1$ & {tex(m.h1)} \\
$h_2$ (confirmation) & {tex(m.h2)} \\
$h_3$ (relevance) & {tex(m.h3)} \\
{qud_row}norms & $P_{{h_2}}${{=}}{tex(m.P_h2)}\quad$P_{{h_3}}${{=}}{tex(m.P_h3)}\quad$C_{{h_2}}${{=}}{tex(m.C_h2)}\quad$C_{{h_3}}${{=}}{tex(m.C_h3)} \\
\end{{tabular}}\\[7pt]""")

OUT.write_text('% Generated by gen/make_appendix_items.py -- do not edit by hand.\n'
               '\\small\n' + '\n'.join(rows) + '\n\\normalsize\n')
print(f'{OUT.name} — {len(rows)} items')
